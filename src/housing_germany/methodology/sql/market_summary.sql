-- Build SQL for MARKET_SUMMARY, recovered verbatim from TASK_REFRESH_MARKET_SUMMARY on 2026-10-20.
-- {target} is replaced by the pipeline (built as <TABLE>_NEXT, checked, then swapped).
CREATE OR REPLACE TABLE {target} AS
WITH latest_dates AS (
    SELECT PLACE_ID, PLACE_TYPE, TRANSACTION_TYPE, ITEM_TYPE,
           MAX(INDEX_DATE) AS LATEST_DATE,
           MIN(INDEX_DATE) AS FIRST_DATE
    FROM HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES
    GROUP BY 1,2,3,4
),
latest_vals AS (
    SELECT ld.PLACE_ID, ld.PLACE_TYPE, ld.TRANSACTION_TYPE, ld.ITEM_TYPE,
           ld.LATEST_DATE, ld.FIRST_DATE,
           s.INDEX_VALUE AS LATEST_INDEX,
           f.INDEX_VALUE AS FIRST_INDEX,
           m1.INDEX_VALUE AS IDX_1M,
           m3.INDEX_VALUE AS IDX_3M,
           m6.INDEX_VALUE AS IDX_6M,
           ytd.INDEX_VALUE AS IDX_YTD,
           y1.INDEX_VALUE AS IDX_1Y,
           y2.INDEX_VALUE AS IDX_2Y,
           y3.INDEX_VALUE AS IDX_3Y,
           y5.INDEX_VALUE AS IDX_5Y
    FROM latest_dates ld
    JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES s
      ON ld.PLACE_ID = s.PLACE_ID AND ld.PLACE_TYPE = s.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = s.TRANSACTION_TYPE AND ld.ITEM_TYPE = s.ITEM_TYPE
     AND s.INDEX_DATE = ld.LATEST_DATE
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES f
      ON ld.PLACE_ID = f.PLACE_ID AND ld.PLACE_TYPE = f.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = f.TRANSACTION_TYPE AND ld.ITEM_TYPE = f.ITEM_TYPE
     AND f.INDEX_DATE = ld.FIRST_DATE
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES m1
      ON ld.PLACE_ID = m1.PLACE_ID AND ld.PLACE_TYPE = m1.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = m1.TRANSACTION_TYPE AND ld.ITEM_TYPE = m1.ITEM_TYPE
     AND m1.INDEX_DATE = DATEADD('month', -1, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES m3
      ON ld.PLACE_ID = m3.PLACE_ID AND ld.PLACE_TYPE = m3.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = m3.TRANSACTION_TYPE AND ld.ITEM_TYPE = m3.ITEM_TYPE
     AND m3.INDEX_DATE = DATEADD('month', -3, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES m6
      ON ld.PLACE_ID = m6.PLACE_ID AND ld.PLACE_TYPE = m6.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = m6.TRANSACTION_TYPE AND ld.ITEM_TYPE = m6.ITEM_TYPE
     AND m6.INDEX_DATE = DATEADD('month', -6, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES ytd
      ON ld.PLACE_ID = ytd.PLACE_ID AND ld.PLACE_TYPE = ytd.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = ytd.TRANSACTION_TYPE AND ld.ITEM_TYPE = ytd.ITEM_TYPE
     AND ytd.INDEX_DATE = DATE_TRUNC('year', ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES y1
      ON ld.PLACE_ID = y1.PLACE_ID AND ld.PLACE_TYPE = y1.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = y1.TRANSACTION_TYPE AND ld.ITEM_TYPE = y1.ITEM_TYPE
     AND y1.INDEX_DATE = DATEADD('year', -1, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES y2
      ON ld.PLACE_ID = y2.PLACE_ID AND ld.PLACE_TYPE = y2.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = y2.TRANSACTION_TYPE AND ld.ITEM_TYPE = y2.ITEM_TYPE
     AND y2.INDEX_DATE = DATEADD('year', -2, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES y3
      ON ld.PLACE_ID = y3.PLACE_ID AND ld.PLACE_TYPE = y3.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = y3.TRANSACTION_TYPE AND ld.ITEM_TYPE = y3.ITEM_TYPE
     AND y3.INDEX_DATE = DATEADD('year', -3, ld.LATEST_DATE)
    LEFT JOIN HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.INDEX_SERIES y5
      ON ld.PLACE_ID = y5.PLACE_ID AND ld.PLACE_TYPE = y5.PLACE_TYPE
     AND ld.TRANSACTION_TYPE = y5.TRANSACTION_TYPE AND ld.ITEM_TYPE = y5.ITEM_TYPE
     AND y5.INDEX_DATE = DATEADD('year', -5, ld.LATEST_DATE)
),
prices AS (
    SELECT PLACE_ID, PLACE_TYPE, TRANSACTION_TYPE, ITEM_TYPE, VALUE AS PRICE_SQM, ACCURACY,
           ROW_NUMBER() OVER (PARTITION BY PLACE_ID, PLACE_TYPE, TRANSACTION_TYPE, ITEM_TYPE
                              ORDER BY PRICE_DATE DESC) AS RN
    FROM SILVER_PROD.MKKN_PRICE.PRICE_DE
    WHERE ACCURACY >= 3
)
SELECT
    lv.PLACE_ID,
    lv.PLACE_TYPE,
    lv.TRANSACTION_TYPE,
    lv.ITEM_TYPE,
    lv.LATEST_DATE,
    lv.LATEST_INDEX,
    p.PRICE_SQM,
    p.ACCURACY AS PRICE_ACCURACY,
    CASE WHEN IDX_1M > 0 THEN (LATEST_INDEX - IDX_1M) / IDX_1M END AS VAR_1M,
    CASE WHEN IDX_3M > 0 THEN (LATEST_INDEX - IDX_3M) / IDX_3M END AS VAR_3M,
    CASE WHEN IDX_6M > 0 THEN (LATEST_INDEX - IDX_6M) / IDX_6M END AS VAR_6M,
    CASE WHEN IDX_YTD > 0 THEN (LATEST_INDEX - IDX_YTD) / IDX_YTD END AS VAR_YTD,
    CASE WHEN IDX_1Y > 0 THEN (LATEST_INDEX - IDX_1Y) / IDX_1Y END AS VAR_1Y,
    CASE WHEN IDX_2Y > 0 THEN (LATEST_INDEX - IDX_2Y) / IDX_2Y END AS VAR_2Y,
    CASE WHEN IDX_3Y > 0 THEN (LATEST_INDEX - IDX_3Y) / IDX_3Y END AS VAR_3Y,
    CASE WHEN IDX_5Y > 0 THEN (LATEST_INDEX - IDX_5Y) / IDX_5Y END AS VAR_5Y,
    CASE WHEN FIRST_INDEX > 0 THEN (LATEST_INDEX - FIRST_INDEX) / FIRST_INDEX END AS VAR_ALL
FROM latest_vals lv
LEFT JOIN prices p
  ON lv.PLACE_ID = p.PLACE_ID AND lv.PLACE_TYPE = p.PLACE_TYPE
 AND lv.TRANSACTION_TYPE = p.TRANSACTION_TYPE
 AND REPLACE(lv.ITEM_TYPE, 'ITEM_TYPE.', '') = p.ITEM_TYPE
 AND p.RN = 1
