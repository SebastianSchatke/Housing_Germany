"""
Generate methodologies/<id>/README.md from the spec files.

Docs are derived from the specs, never written by hand, so they cannot drift
from what RUN_METHODOLOGY executes. Run after editing a spec and commit the
result with it. --check exits non-zero if any README is out of date (for CI).

Usage: python scripts/document_methodologies.py [--check]
"""
from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parents[1]


def _fmt(value) -> str:
    if isinstance(value, list):
        return ", ".join(f"`{v}`" for v in value)
    return f"`{value}`" if not isinstance(value, str) or " " not in value else value


def render(specs: list[dict]) -> str:
    latest = specs[-1]
    lines = [
        f"# {latest['title']}",
        "",
        f"<!-- Generated by scripts/document_methodologies.py from v*.yaml. Do not edit. -->",
        "",
        f"**Id:** `{latest['id']}`  ",
        f"**Owner:** {latest.get('owner', 'n/a')}  ",
        "**Versions:** " + ", ".join(f"v{s['version']} ({s['status']})" for s in specs),
        "",
        "## Answers questions like",
        *[f"- {q}" for q in latest.get("question_patterns", [])],
        "",
        "## Inputs",
        "| Parameter | Allowed values | Default | Required |",
        "|---|---|---|---|",
    ]
    for name, rule in latest["inputs"].items():
        allowed = rule.get("allowed") or rule.get("levels") or ""
        lines.append(f"| `{name}` | {_fmt(allowed) if allowed else 'any'} | "
                     f"{_fmt(rule['default']) if 'default' in rule else ''} | "
                     f"{'yes' if rule.get('required') else ''} |")
    lines += ["", "## Sources", *[f"- `{s}`" for s in latest["sources"]], "",
              "## Implementation", *[f"- **{k}:** `{v}`" for k, v in latest["implementation"].items()], ""]
    if latest.get("fixed_choices"):
        lines += ["## Fixed calculation choices",
                  "These cannot be changed per request; changing them requires a new version.", "",
                  *[f"- **{k}:** {v}" for k, v in latest["fixed_choices"].items()], ""]
    lines += ["## Outputs", f"- Table: `{latest['outputs']['table']}`"]
    if "grain" in latest["outputs"]:
        lines.append(f"- Grain: {_fmt(latest['outputs']['grain'])}")
    if "columns" in latest["outputs"]:
        lines.append(f"- Columns: {_fmt(latest['outputs']['columns'])}")
    lines += ["", "## Quality checks"]
    for c in latest["checks"]:
        detail = ", ".join(f"{k}={v}" for k, v in c.items() if k != "type")
        lines.append(f"- `{c['type']}`" + (f": {detail}" if detail else ""))
    if latest.get("open_questions"):
        lines += ["", "## Open questions", *[f"- {' '.join(str(q).split())}" for q in latest["open_questions"]]]
    lines += ["", "## How to run",
              "```sql",
              f"CALL HOUSING_DEV.MARKET_INSIGHTS_AGENTS.RUN_METHODOLOGY('{latest['id']}', PARSE_JSON('{{\"geography\": \"AD02DE1\"}}'));",
              "```", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for folder in sorted(p for p in (REPO / "methodologies").iterdir() if p.is_dir()):
        specs = sorted((yaml.safe_load(f.read_text()) for f in folder.glob("v*.yaml")),
                       key=lambda s: s["version"])
        if not specs:
            continue
        text = render(specs)
        readme = folder / "README.md"
        if readme.exists() and readme.read_text() == text:
            continue
        stale.append(str(readme.relative_to(REPO)))
        if not args.check:
            readme.write_text(text)
    if args.check and stale:
        sys.exit("Out of date: " + ", ".join(stale) + " (run scripts/document_methodologies.py)")
    print(("updated: " + ", ".join(stale)) if stale else "all READMEs up to date")


if __name__ == "__main__":
    main()
