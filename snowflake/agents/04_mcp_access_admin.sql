-- (exposes only the HOUSING_ANALYST agent). The steps below need an account
-- admin (security integration, role creation, user defaults).

-- 1. Least-privileged access role
CREATE ROLE IF NOT EXISTS R_HOUSING_ANALYST_MCP_USER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON WAREHOUSE WH_HOUSING_DEV TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON DATABASE HOUSING_DEV TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON SCHEMA HOUSING_DEV.MARKET_INSIGHTS_AGENTS TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON SCHEMA HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON MCP SERVER HOUSING_DEV.MARKET_INSIGHTS_AGENTS.HOUSING_ANALYST_MCP TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON AGENT HOUSING_DEV.MARKET_INSIGHTS_AGENTS.HOUSING_ANALYST TO ROLE R_HOUSING_ANALYST_MCP_USER;

-- Agent tools (procedures run as caller, so the role needs what they read and write)
GRANT USAGE ON PROCEDURE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.AGENT_RUN_METHODOLOGY(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR) TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON PROCEDURE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.AGENT_REPORT_GAP(VARCHAR, VARCHAR, VARCHAR) TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON PROCEDURE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.LIST_METHODOLOGIES() TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT USAGE ON CORTEX SEARCH SERVICE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.METHODOLOGY_SEARCH TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON SEMANTIC VIEW HOUSING_DEV.MARKET_INSIGHTS_AGENTS.SV_HOUSING_MARKET TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT READ ON STAGE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.CODE TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.METHODOLOGY_REGISTRY TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON VIEW HOUSING_DEV.MARKET_INSIGHTS_AGENTS.APPROVED_METHODOLOGIES TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT, INSERT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.RUN_LOG TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT INSERT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.RUN_RESULTS TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT INSERT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_AGENTS.ISSUES TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.MARKET_SUMMARY TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.GEO_PLACES TO ROLE R_HOUSING_ANALYST_MCP_USER;
GRANT SELECT ON TABLE HOUSING_DEV.MARKET_INSIGHTS_STREAMLIT_APPS.LISTINGS_INSIGHTS TO ROLE R_HOUSING_ANALYST_MCP_USER;
