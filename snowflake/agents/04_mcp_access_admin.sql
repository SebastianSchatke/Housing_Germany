-- 2. OAuth integration (one per client type; Claude example uses PKCE)
CREATE SECURITY INTEGRATION IF NOT EXISTS HOUSING_ANALYST_MCP_OAUTH
  TYPE = OAUTH
  OAUTH_CLIENT = CUSTOM
  ENABLED = TRUE
  OAUTH_CLIENT_TYPE = 'PUBLIC'
  OAUTH_REDIRECT_URI = 'https://claude.ai/api/mcp/auth_callback'
  OAUTH_USE_SECONDARY_ROLES = NONE
  ALLOWED_ROLES_LIST = ('R_HOUSING_ANALYST_MCP_USER');
